    # ══════════════════════════════════════════════════════════
    #  10. TIMELINE (auto-positioned)
    # ══════════════════════════════════════════════════════════

    def _spec_timeline(self, spec, plan, sc, design, img, colors):
        if not sc:
            return

        spec.add(shape_element("rectangle", 0, 0, SLIDE_W, 0.06, fill_color=colors["primary"]))
        spec.add(title_element(sc.title, font_size=design.fonts.title_size_pt, color=colors["text_primary"]))

        points = sc.bullet_points or []
        milestones = compute_timeline_positions(len(points), design.slide_width_inches)

        # Horizontal timeline bar
        spec.add(shape_element(
            "rectangle", MARGIN, 3.8, SLIDE_W - 2 * MARGIN, 0.06,
            fill_color=colors["primary"],
        ))

        for i, (point, ms) in enumerate(zip(points[:7], milestones)):
            dot_size = 0.35

            # Milestone dot
            spec.add(shape_element(
                "oval", ms["cx"] - dot_size / 2, ms["bar_y"] - dot_size / 2 + 0.03,
                dot_size, dot_size,
                fill_color=colors["primary"],
            ))

            # Inner dot
            spec.add(shape_element(
                "oval", ms["cx"] - 0.075, ms["bar_y"] - 0.045,
                0.15, 0.15,
                fill_color=colors["background"],
            ))

            # Label (alternating above/below)
            label_y = ms["label_y_above"] if ms["is_above"] else ms["label_y_below"]
            spec.add(text_element(
                point,
                left=ms["cx"] - ms["label_width"] / 2, top=label_y,
                width=ms["label_width"], height=1.2,
                font_size=design.fonts.caption_size_pt,
                color=colors["text_primary"], alignment="center",
            ))

        if sc.notes:
            spec.notes = sc.notes

    # ══════════════════════════════════════════════════════════
    #  11. QUOTE
    # ══════════════════════════════════════════════════════════

    def _spec_quote(self, spec, plan, sc, design, img, colors):
        if not sc:
            return

        # Opening quotation mark
        spec.add(text_element(
            "\u201C", left=1.5, top=1.2, width=2, height=2,
            font_size=120, color=colors["primary"], alignment="left",
        ))

        # Quote text
        quote_text = sc.body_text or sc.title
        spec.add(SlideElement(
            element_type=ElementType.TEXT,
            position=Position(left=2.0, top=2.5, width=9.3, height=3.0),
            content=quote_text,
            text_style=TextStyle(
                font_size=28, italic=True,
                color=colors["text_primary"], alignment="center",
            ),
        ))

        # Attribution
        if sc.subtitle:
            spec.add(text_element(
                f"— {sc.subtitle}",
                left=2.0, top=5.0, width=9.3, height=0.6,
                font_size=18, color=colors["text_secondary"], alignment="center",
            ))

        # Closing quotation mark
        spec.add(text_element(
            "\u201D", left=10, top=4.5, width=2, height=2,
            font_size=120, color=colors["primary"], alignment="right",
        ))

        # Bottom accent
        spec.add(divider_element(left=5.5, top=5.8, width=2.3, color=colors["accent"]))

        if sc.notes:
            spec.notes = sc.notes

