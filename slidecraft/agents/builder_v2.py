    #  12. THANK YOU
    # ══════════════════════════════════════════════════════════

    def _spec_thank_you(self, spec, plan, sc, design, img, colors):
        # Decorative circles
        spec.add(SlideElement(
            element_type=ElementType.SHAPE,
            position=Position(left=-1, top=-1, width=4, height=4),
            shape_type="oval",
            shape_style=ShapeStyle(fill_color=colors["surface"]),
            z_order=-1,
        ))
        spec.add(SlideElement(
            element_type=ElementType.SHAPE,
            position=Position(left=SLIDE_W - 3, top=SLIDE_H - 3, width=5, height=5),
            shape_type="oval",
            shape_style=ShapeStyle(fill_color=colors["surface"]),
            z_order=-1,
        ))

        # Main text
        spec.add(title_element(
            sc.title if sc else "谢谢！",
            left=2, top=2.2, width=9.3, height=1.5,
            font_size=52, color=colors["primary"],
        ))
        # Override alignment to center
        spec.elements[-1].text_style.alignment = "center"

        if sc and sc.subtitle:
            spec.add(subtitle_element(
                sc.subtitle, left=2, top=3.8, width=9.3, height=0.8,
                font_size=24, color=colors["text_secondary"],
            ))
            spec.elements[-1].text_style.alignment = "center"

        # Accent line
        spec.add(divider_element(left=5.0, top=4.8, width=3.3, color=colors["primary"]))

        # Contact info
        if sc and sc.bullet_points:
            spec.add(bullets_element(
                sc.bullet_points[:3],
                left=3, top=5.3, width=7.3, height=1.5,
                font_size=14, color=colors["text_secondary"],
            ))
